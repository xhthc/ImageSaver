// Writes ui/public/THIRD_PARTY_NOTICES.txt (shipped as popup/THIRD_PARTY_NOTICES.txt): the licence text of every
// bundled dependency of the UI build, plus the notice for copied shadcn/ui component sources.
// Usage (from ui/): node scripts/gen-notices.mjs     Needs `npm ci`.
import fs from "node:fs"
import path from "node:path"
import os from "node:os"
import { spawnSync } from "node:child_process"

const ui = path.resolve(import.meta.dirname, "..")
const npm = process.platform === "win32" ? "npm.cmd" : "npm"
const ls = spawnSync(npm, ["ls", "--omit=dev", "--all", "--json", "--long"], { cwd: ui, encoding: "utf8", shell: process.platform === "win32", maxBuffer: 64 * 1024 * 1024 })
const tree = JSON.parse(ls.stdout)
const found = new Map()
const visit = (deps) => {
  for (const [name, info] of Object.entries(deps || {})) {
    if (info.path && fs.existsSync(info.path)) found.set(`${name}@${info.version}`, info)
    visit(info.dependencies)
  }
}
visit(tree.dependencies)

// Only the packages that really reached the bundle: a build with source maps into a temporary folder lists them.
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'image-saver-notices-'))
const build = spawnSync(process.execPath, [path.join(ui, 'node_modules', 'vite', 'bin', 'vite.js'), 'build', '--outDir', tmp, '--emptyOutDir', '--sourcemap'], { cwd: ui, encoding: 'utf8' })
if (build.status !== 0) throw new Error('build failed: ' + build.stderr.slice(-800))
const bundled = new Set()
for (const f of fs.readdirSync(path.join(tmp, 'assets')).filter((n) => n.endsWith('.map'))) {
  for (const src of JSON.parse(fs.readFileSync(path.join(tmp, 'assets', f), 'utf8')).sources) {
    const i = src.lastIndexOf('node_modules/')
    if (i < 0) continue
    const parts = src.slice(i + 'node_modules/'.length).split('/')
    bundled.add(parts[0].startsWith('@') ? parts[0] + '/' + parts[1] : parts[0])
  }
}
// CSS imports are absent from the JavaScript source maps, but their styles ship in the bundle.
for (const name of ['tailwindcss', 'tw-animate-css']) {
  const directory = path.join(ui, 'node_modules', name)
  const pkg = JSON.parse(fs.readFileSync(path.join(directory, 'package.json'), 'utf8'))
  found.set(`${name}@${pkg.version}`, { path: directory })
  bundled.add(name)
}
fs.rmSync(tmp, { recursive: true, force: true })
for (const key of [...found.keys()]) if (!bundled.has(key.slice(0, key.lastIndexOf('@')))) found.delete(key)

const licenseFile = (dir) => {
  const names = fs.readdirSync(dir).filter((f) => /^(licen[sc]e|copying|notice)/i.test(f)).sort()
  return names.map((f) => fs.readFileSync(path.join(dir, f), "utf8").replace(/\r\n/g, "\n").trim()).join("\n\n")
}
const out = []
out.push("Image Saver extension pages (popup/): third-party notices")
out.push("=".repeat(58))
out.push("")
out.push("The compact popup and the full page are built (ui/, committed output in popup/) from React, shadcn/ui component")
out.push("sources, Tailwind CSS, Radix UI primitives and Lucide icons. The licence text of every bundled dependency of the")
out.push("build that reached the shipped bundle follows (JavaScript source maps and the two direct CSS imports).")
out.push("")
out.push("shadcn/ui (https://ui.shadcn.com) - MIT. The component sources under ui/src/components/ui were generated by the shadcn CLI")
out.push("and are part of this project's source, as the shadcn/ui licence allows. Copyright (c) 2023 shadcn.")
out.push(fs.readFileSync(path.join(ui, 'licenses/shadcn-ui.txt'), 'utf8').trim())
out.push("")
out.push("Tailwind CSS preflight/styles and tw-animate-css animation utilities ship in the generated stylesheet; their full notices follow.")
out.push("")
out.push("-".repeat(58))
for (const key of [...found.keys()].sort()) {
  const info = found.get(key)
  const pkg = JSON.parse(fs.readFileSync(path.join(info.path, "package.json"), "utf8"))
  const license = typeof pkg.license === "string" ? pkg.license : (pkg.license && pkg.license.type) || "see licence text"
  out.push("")
  out.push(`${key} - ${license}`)
  if (pkg.homepage || (pkg.repository && (pkg.repository.url || pkg.repository))) out.push(String(pkg.homepage || pkg.repository.url || pkg.repository))
  // This npm package omits its MIT file; ship the complete upstream notice with this pinned version.
  const text = licenseFile(info.path) || (key === 'react-remove-scroll-bar@2.3.8' ? fs.readFileSync(path.join(ui, 'licenses/react-remove-scroll-bar.txt'), 'utf8').trim() : '')
  if (!text) throw new Error(`Missing licence text for bundled package ${key}`)
  out.push("")
  out.push(text)
  out.push("")
  out.push("-".repeat(58))
}
fs.mkdirSync(path.join(ui, "public"), { recursive: true })
fs.writeFileSync(path.join(ui, "public", "THIRD_PARTY_NOTICES.txt"), out.join("\n") + "\n")
console.log(`notices for ${found.size} packages written to ui/public/THIRD_PARTY_NOTICES.txt`)
